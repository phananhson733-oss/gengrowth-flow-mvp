#!/usr/bin/env node
// gg-cluster-viz.mjs — emit mermaid graphs for cluster ⇆ page topology.
//
// Source of truth = workbook tabs:
//   主题集群表 (clusters)  : cluster_id / cluster_name / pillar_page / page_assets / track
//   选题登记表 (pages)     : page_id / cluster_id / page_role / template / tier / Target Keyword
//
// Output: one mermaid graph per cluster. Nodes = pages, edges = pillar←spoke,
// shape encodes role, fill encodes published status (✅ / pending).
//
// Usage:
//   node tools/scripts/gg-cluster-viz.mjs                       # md to stdout
//   node tools/scripts/gg-cluster-viz.mjs --out docs/CLUSTERS.mermaid.md
//   node tools/scripts/gg-cluster-viz.mjs --cluster fam-aura    # one cluster
//   node tools/scripts/gg-cluster-viz.mjs --workbook flow-mvp|legacy|<id>
//
// Exit: 0 ok, 1 fk-error, 2 cli/env.

import { writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { loadEnv, gFetch } from './lib/gg-shared.mjs';
import { getAccessToken } from './lib/_oauth-token.mjs';

const TAB = {
  PAGES: '选题登记表',
  CLUSTERS: '主题集群表',
};

function parseArgs(argv) {
  const out = {};
  for (let i = 0; i < argv.length; i++) {
    const a = argv[i];
    if (!a.startsWith('--')) continue;
    const key = a.slice(2).replace(/-/g, '_');
    const next = argv[i + 1];
    if (next === undefined || next.startsWith('--')) out[key] = true;
    else { out[key] = next; i++; }
  }
  return out;
}

function usage() {
  process.stdout.write(`gg-cluster-viz.mjs — cluster topology mermaid graphs

usage:
  node tools/scripts/gg-cluster-viz.mjs                       # md to stdout
  node tools/scripts/gg-cluster-viz.mjs --out docs/CLUSTERS.mermaid.md
  node tools/scripts/gg-cluster-viz.mjs --cluster fam-aura
  node tools/scripts/gg-cluster-viz.mjs --workbook flow-mvp|legacy|<id>
`);
}

function indexOfHeader(headerRow, name) {
  for (let i = 0; i < headerRow.length; i++) {
    if (String(headerRow[i] || '').trim() === name) return i;
  }
  return -1;
}

async function fetchTab(workbookId, tabName, token) {
  const r = await gFetch(
    `https://sheets.googleapis.com/v4/spreadsheets/${workbookId}/values/${encodeURIComponent(tabName)}`,
    token,
  );
  return r.values || [];
}

// Sanitize node id for mermaid (alpha-numeric + underscore only).
function nodeId(s) {
  return String(s || 'unknown').replace(/[^A-Za-z0-9_]/g, '_').slice(0, 40);
}

// Truncate label for mermaid; quote if contains special.
function nodeLabel(s) {
  const trimmed = String(s || '').trim().slice(0, 50);
  if (!trimmed) return 'unknown';
  // Replace " with ' for mermaid safety.
  return trimmed.replace(/"/g, "'");
}

function buildGraphs(clustersRows, pagesRows, filterCluster) {
  const cH = clustersRows[0] || [];
  const pH = pagesRows[0] || [];
  const idxClusterId = indexOfHeader(cH, 'cluster_id');
  const idxClusterName = indexOfHeader(cH, 'cluster_name');
  const idxClusterPillar = indexOfHeader(cH, 'pillar_page');
  const idxClusterTrack = indexOfHeader(cH, 'track');
  const idxPagePageId = indexOfHeader(pH, 'page_id');
  const idxPageClusterId = indexOfHeader(pH, 'cluster_id');
  const idxPageRole = indexOfHeader(pH, 'page_role');
  const idxPageTier = indexOfHeader(pH, 'Tier');
  const idxPageTarget = indexOfHeader(pH, 'Target Keyword');
  const idxPageStatus = indexOfHeader(pH, 'Status');

  // Group pages by cluster_id.
  const byCluster = new Map();
  for (let i = 1; i < pagesRows.length; i++) {
    const r = pagesRows[i];
    const cid = String(r[idxPageClusterId] || '').trim();
    if (!cid) continue;
    if (!byCluster.has(cid)) byCluster.set(cid, []);
    byCluster.get(cid).push({
      page_id: String(r[idxPagePageId] || '').trim() || `row${i + 1}`,
      page_role: String(r[idxPageRole] || '').trim(),
      tier: String(r[idxPageTier] || '').trim(),
      target_keyword: String(r[idxPageTarget] || '').trim(),
      status: String(r[idxPageStatus] || '').trim(),
    });
  }

  const graphs = [];
  for (let i = 1; i < clustersRows.length; i++) {
    const r = clustersRows[i];
    const cid = String(r[idxClusterId] || '').trim();
    if (!cid) continue;
    if (filterCluster && cid !== filterCluster) continue;
    const cname = String(r[idxClusterName] || '').trim();
    const pillar = String(r[idxClusterPillar] || '').trim();
    const track = String(r[idxClusterTrack] || '').trim();
    const pages = byCluster.get(cid) || [];

    graphs.push({
      cluster_id: cid,
      cluster_name: cname,
      pillar_page: pillar,
      track,
      pages,
    });
  }
  return graphs;
}

function renderMermaid(graphs) {
  const out = [];
  out.push(`# Cluster Topology — ${new Date().toISOString().slice(0, 10)}`);
  out.push('');
  out.push(`Generated by \`gg-cluster-viz.mjs\`. ${graphs.length} cluster(s).`);
  out.push('');

  for (const g of graphs) {
    out.push(`## ${g.cluster_id} — ${g.cluster_name || '(no name)'}`);
    out.push('');
    if (g.track) out.push(`- Track: \`${g.track}\``);
    if (g.pillar_page) out.push(`- Pillar: \`${g.pillar_page}\``);
    out.push(`- Pages: ${g.pages.length}`);
    out.push('');

    if (g.pages.length === 0) {
      out.push('_(no pages assigned)_');
      out.push('');
      continue;
    }

    // mermaid block
    out.push('```mermaid');
    out.push('graph TD');
    const clusterNode = nodeId(`cluster_${g.cluster_id}`);
    out.push(`  ${clusterNode}["📦 ${nodeLabel(g.cluster_id)}"]:::cluster`);

    // Determine pillar: explicit pillar_page or first page_role=Pillar
    let pillarPage = g.pillar_page;
    if (!pillarPage) {
      const p = g.pages.find((pg) => /pillar/i.test(pg.page_role));
      if (p) pillarPage = p.page_id;
    }

    // Emit nodes
    for (const p of g.pages) {
      const id = nodeId(p.page_id);
      const isPillar = pillarPage && p.page_id === pillarPage;
      const isPublished = /发布|published|✅/.test(p.status);
      const role = p.page_role || '(no role)';
      const tier = p.tier || '';
      const tag = isPillar ? '🏛️' : isPublished ? '✅' : '⬜';
      const label = `${tag} ${nodeLabel(p.page_id)}<br/>${nodeLabel(role)}${tier ? '<br/>' + nodeLabel(tier) : ''}`;
      out.push(`  ${id}["${label}"]:::${isPublished ? 'pub' : isPillar ? 'pillar' : 'draft'}`);
      out.push(`  ${clusterNode} --> ${id}`);
    }
    out.push('  classDef cluster fill:#1976d2,stroke:#fff,color:#fff,font-weight:bold');
    out.push('  classDef pillar fill:#f57c00,stroke:#fff,color:#fff');
    out.push('  classDef pub fill:#388e3c,stroke:#fff,color:#fff');
    out.push('  classDef draft fill:#eceff1,stroke:#90a4ae,color:#37474f');
    out.push('```');
    out.push('');
  }
  return out.join('\n');
}

async function main() {
  const args = parseArgs(process.argv.slice(2));
  if (args.help || args.h) { usage(); process.exit(0); }
  loadEnv();

  let workbookId;
  const wbArg = args.workbook;
  if (wbArg && wbArg !== true && wbArg !== 'flow-mvp' && wbArg !== 'legacy') {
    workbookId = String(wbArg);
  } else if (wbArg === 'legacy') {
    workbookId = process.env.GG_SHEETS_WORKBOOK_ID;
  } else {
    workbookId = process.env.GG_SHEETS_FLOW_MVP_WORKBOOK_ID || process.env.GG_SHEETS_WORKBOOK_ID;
  }
  if (!workbookId) {
    process.stderr.write('ERROR: GG_SHEETS_FLOW_MVP_WORKBOOK_ID (or legacy) missing\n');
    process.exit(2);
  }

  const token = await getAccessToken();
  const [clusters, pages] = await Promise.all([
    fetchTab(workbookId, TAB.CLUSTERS, token),
    fetchTab(workbookId, TAB.PAGES, token),
  ]);

  const filter = args.cluster && args.cluster !== true ? String(args.cluster) : null;
  const graphs = buildGraphs(clusters, pages, filter);

  if (graphs.length === 0) {
    process.stderr.write(`no clusters matched${filter ? ` (filter: ${filter})` : ''}\n`);
    process.exit(filter ? 1 : 0);
  }

  const md = renderMermaid(graphs);
  if (args.out) {
    const outPath = resolve(String(args.out));
    writeFileSync(outPath, md);
    process.stderr.write(`wrote ${graphs.length} cluster graph(s) → ${outPath}\n`);
  } else {
    process.stdout.write(md);
  }
  process.exit(0);
}

main().catch((e) => {
  process.stderr.write(`FATAL: ${e.message}\n`);
  process.exit(2);
});
